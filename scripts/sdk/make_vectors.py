#!/usr/bin/env python3
"""
Test vectors for the TypeScript SDK (sdk/typescript), computed by the node's own code: what a
wallet has to produce byte for byte. Writes ``sdk/typescript/test/vectors.json`` and the op-code
table ``sdk/typescript/src/ops.ts``.

The key is kept from the existing vectors file, so a rerun changes nothing unless the node's
formats did. Signatures are randomized (hedged ML-DSA), so they are verified, never compared.
``tests/test_sdk_vectors.py`` fails when the committed files are stale, and checks the smart
account's values against the contract running in the QRDX EVM.

    python scripts/sdk/make_vectors.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

SDK = ROOT / "sdk" / "typescript"
VECTORS = SDK / "test" / "vectors.json"
OPS = SDK / "src" / "ops.ts"

PROXY_HEAD = bytes.fromhex("3d602d80600a3d3981f3363d3d373d3d3d363d73")
PROXY_TAIL = bytes.fromhex("5af43d82803e903d91602b57fd5bf3")
CALLS = "(address,uint256,bytes)[]"


def _key():
    from qrdx.crypto.pq.dilithium import PQPrivateKey

    if VECTORS.exists():
        k = json.loads(VECTORS.read_text())["key"]
        return PQPrivateKey.from_hex(k["secret_key"], public_key_hex=k["public_key"])
    return PQPrivateKey.generate()


def _sel(signature: str) -> bytes:
    from eth_utils import keccak

    return keccak(text=signature)[:4]


def ops_table() -> str:
    from qrdx.exchange.transactions import ExchangeOpType

    rows = "\n".join(f"  {m.name}: {int(m)}," for m in ExchangeOpType)
    return (
        "// Generated by scripts/sdk/make_vectors.py from qrdx.exchange.transactions.ExchangeOpType.\n"
        "// Do not edit: tests/test_sdk_vectors.py fails when it is stale.\n\n"
        "export const EXCHANGE_OPS = {\n"
        f"{rows}\n"
        "} as const;\n\n"
        "export type ExchangeOpName = keyof typeof EXCHANGE_OPS;\n"
    )


def build(key=None) -> dict:
    from eth_abi import encode
    from eth_utils import keccak

    from qrdx import predeploys
    from qrdx.exchange.transactions import ExchangeOpType, ExchangeTransaction
    from qrdx.transactions.pq_tx import PQTransaction

    key = key or _key()
    pub = key.public_key
    address = pub.to_address()
    out: dict = {
        "note": "Test vectors for sdk/typescript. The key is a test key: never fund it.",
        "key": {
            "secret_key": key.to_hex(),
            "public_key": pub.to_hex(),
            "address": address,
            "account_id": pub.to_account_id(),
            "key_hash": "0x" + keccak(pub.to_bytes()).hex(),
        },
        "account_ids": {
            "0x" + "AB" * 20: "0x" + "ab" * 20,
            "0xPQ" + "0" * 63 + "1": None,
        },
    }
    from qrdx.crypto.account_id import to_account_id

    out["account_ids"]["0xPQ" + "0" * 63 + "1"] = to_account_id("0xPQ" + "0" * 63 + "1")

    pyjson = [
        {"b": 1, "a": [True, False, None], "c": {"z": "é中", "y": -5}},
        {"emoji": "😀", "ctl": "\x01\n\t\"\\\x7f", "": 0},
        [],
        {},
        {"amount": "1.5", "market_id": "BTC-QRDX-PERP", "nested": [{"k": 2, "j": [1, {"x": "y"}]}]},
    ]
    out["pyjson"] = [{"value": v, "text": json.dumps(v, sort_keys=True)} for v in pyjson]

    agent = "0xPQ" + "c" * 64
    cases = [
        dict(op_type=ExchangeOpType.CANCEL_ALL, sender=address, nonce=0, params={},
             gas_limit=200_000, gas_price=100_000_000, chain_id=7620),
        dict(op_type=ExchangeOpType.PERP_ORDER, sender=address, nonce=7,
             params={"market_id": "BTC-QRDX-PERP", "side": "buy", "size": "0.01",
                     "price": "30000", "tif": "alo", "expires_at": 1_800_000_000},
             gas_limit=1_000_000, gas_price=3_500_000_000, chain_id=762),
        dict(op_type=ExchangeOpType.TOKEN_TRANSFER, sender=address, nonce=2 ** 40,
             params={"token_address": "QRDX", "to": agent, "amount": "12.000000000000000001",
                     "memo": "für dich ✓"},
             gas_limit=150_000, gas_price=10 ** 18, chain_id=9999),
        dict(op_type=ExchangeOpType.PERP_CANCEL, sender=agent, signer=address, nonce=3,
             params={"market_id": "ETH-QRDX-PERP", "order_id": "o-1"},
             gas_limit=120_000, gas_price=0, chain_id=7620),
    ]
    exchange = []
    for c in cases:
        tx = ExchangeTransaction(**c)
        raw = tx.signing_bytes()
        exchange.append({
            "fields": {
                "op": tx.op_type.name, "op_type": int(tx.op_type), "sender": tx.sender,
                "signer": tx.signer, "nonce": str(tx.nonce), "params": tx.params,
                "gas_limit": str(tx.gas_limit), "gas_price": str(tx.gas_price),
                "chain_id": str(tx.chain_id),
            },
            "canonical": raw.hex(),
            "tx_hash": tx.tx_hash(),
            "signature": key.sign(raw).to_bytes().hex(),
        })
    out["exchange"] = exchange

    pq = []
    for to, value, data in ((bytes.fromhex("b0" * 20), 10 ** 18, b""),
                            (None, 0, bytes.fromhex("6000600055")),
                            (bytes.fromhex(predeploys.FACTORY_ADDRESS[2:]), 0, bytes(range(40)))):
        t = PQTransaction(chain_id=7620, nonce=3, gas_price=2_000_000_000, gas_limit=400_000,
                          to=to, value=value, data=data)
        signing = t.signing_hash()
        t.sign(key)
        pq.append({
            "fields": {"chain_id": "7620", "nonce": "3", "gas_price": "2000000000",
                       "gas_limit": "400000", "to": "0x" + to.hex() if to else None,
                       "value": str(value), "data": "0x" + data.hex()},
            "signing_hash": signing.hex(),
            "signature": t.signature.hex(),
            "raw": t.encode().hex(),
            "hash": t.hash().hex(),
            "intrinsic_gas": t.intrinsic_gas(),
        })
    out["pq_tx"] = pq

    domain = keccak(b"QRDX PQSmartAccount v1")
    owner_key = keccak(pub.to_bytes())
    salt = bytes.fromhex("01" * 32)
    factory = bytes.fromhex(predeploys.FACTORY_ADDRESS[2:])
    implementation = bytes.fromhex(predeploys.IMPLEMENTATION_ADDRESS[2:])
    init = PROXY_HEAD + implementation + PROXY_TAIL
    account = keccak(b"\xff" + factory + keccak(encode(["bytes32", "bytes32"], [owner_key, salt]))
                     + keccak(init))[12:]
    calls = [("0x" + "b0" * 20, 10 ** 18, b""),
             ("0x" + predeploys.FACTORY_ADDRESS[2:], 0, _sel("create(bytes32,bytes32)") + bytes(64))]
    nonce, valid_until, chain_id = 5, 1_900_000_000, 7620
    execute_hash = keccak(encode(
        ["bytes32", "uint256", "address", "uint256", "uint256", CALLS],
        [domain, chain_id, "0x" + account.hex(), nonce, valid_until, calls]))
    fake_sig = bytes([0x11]) * 3309
    execute = _sel(f"execute({CALLS},uint256,uint256,bytes,bytes)") + encode(
        [CALLS, "uint256", "uint256", "bytes", "bytes"],
        [calls, nonce, valid_until, pub.to_bytes(), fake_sig])
    message = keccak(b"an application's message")
    bound = keccak(encode(["bytes32", "uint256", "address", "bytes32"],
                          [domain, chain_id, "0x" + account.hex(), message]))
    guardians = ["0x" + "a1" * 20, "0x" + "a2" * 20]
    out["smart_account"] = {
        "domain": "0x" + domain.hex(),
        "chain_id": str(chain_id),
        "owner_key": "0x" + owner_key.hex(),
        "salt": "0x" + salt.hex(),
        "factory": predeploys.FACTORY_ADDRESS,
        "implementation": predeploys.IMPLEMENTATION_ADDRESS,
        "account": "0x" + account.hex(),
        "nonce": str(nonce),
        "valid_until": str(valid_until),
        "calls": [{"target": t, "value": str(v), "data": "0x" + d.hex()} for t, v, d in calls],
        "execute_hash": "0x" + execute_hash.hex(),
        "fake_signature": "0x" + fake_sig.hex(),
        "execute_calldata": "0x" + execute.hex(),
        "message": "0x" + message.hex(),
        "erc1271_digest": "0x" + bound.hex(),
        "erc1271_param": "0x" + encode(["bytes", "bytes"], [pub.to_bytes(), fake_sig]).hex(),
        "create_calldata": "0x" + (_sel("create(bytes32,bytes32)")
                                   + encode(["bytes32", "bytes32"], [owner_key, salt])).hex(),
        "session_calldata": "0x" + (_sel("setSessionKey(bytes32,uint64,uint128)") + encode(
            ["bytes32", "uint64", "uint128"], [owner_key, 1_900_000_000, 5 * 10 ** 18])).hex(),
        "guardians": guardians,
        "guardians_calldata": "0x" + (_sel("setGuardians(address[],uint256,uint256)") + encode(
            ["address[]", "uint256", "uint256"], [guardians, 2, 86_400])).hex(),
    }
    return out


def main() -> int:
    vectors = build()
    VECTORS.parent.mkdir(parents=True, exist_ok=True)
    VECTORS.write_text(json.dumps(vectors, indent=1, ensure_ascii=False) + "\n")
    OPS.write_text(ops_table())
    print(f"wrote {VECTORS.relative_to(ROOT)} and {OPS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
