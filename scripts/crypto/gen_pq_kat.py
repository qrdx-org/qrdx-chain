#!/usr/bin/env python3
"""
Regenerate qrdx/crypto/pq/kat_vectors.py, the known-answer vectors every node checks its liboqs
against at startup (qrdx/crypto/pq/algorithms.py).

The vectors come from implementations independent of liboqs, from fixed seeds, and are checked
both ways against the installed liboqs before anything is written:

    pip install --target /some/dir dilithium-py==1.5.1 kyber-py==1.2.0
    python scripts/crypto/gen_pq_kat.py /some/dir

The output must not change unless the standard does: a different file means one of the three
implementations computes something else, and that is the problem to find.
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "qrdx" / "crypto" / "pq" / "kat_vectors.py"

TEMPLATE = '''"""
Known-answer vectors for the post-quantum algorithms (qrdx/crypto/pq/algorithms.py).

GENERATED by scripts/crypto/gen_pq_kat.py; do not edit. Each vector comes from an independent
implementation of the standard (dilithium-py 1.5.1 for FIPS 204, kyber-py 1.2.0 for FIPS 203)
from fixed seeds, and was checked both ways against liboqs {liboqs} when generated.
"""

# ML-DSA-65 (FIPS 204), pure, empty context: a deterministic signature over MESSAGE.
ML_DSA_65_PUBLIC_KEY = "{pk}"
ML_DSA_65_MESSAGE = "{msg}"
ML_DSA_65_SIGNATURE = "{sig}"

# ML-KEM-768 (FIPS 203): decapsulating CIPHERTEXT with SECRET_KEY gives SHARED_SECRET.
ML_KEM_768_SECRET_KEY = "{dk}"
ML_KEM_768_CIPHERTEXT = "{ct}"
ML_KEM_768_SHARED_SECRET = "{ss}"
'''


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    sys.path.insert(0, sys.argv[1])
    import oqs
    from dilithium_py.ml_dsa import ML_DSA_65
    from kyber_py.ml_kem import ML_KEM_768

    # ML-DSA-65: the reference signs, liboqs verifies; liboqs signs, the reference verifies.
    pk, sk = ML_DSA_65.key_derive(hashlib.sha256(b"qrdx kat ml-dsa-65").digest())
    msg = b"QRDX known-answer test: ML-DSA-65 (FIPS 204), pure, empty context"
    sig = ML_DSA_65.sign(sk, msg, deterministic=True)
    if not oqs.Signature("ML-DSA-65").verify(msg, sig, pk):
        raise SystemExit("liboqs rejects the reference ML-DSA-65 signature")
    if not ML_DSA_65.verify(pk, msg, oqs.Signature("ML-DSA-65", sk).sign(msg)):
        raise SystemExit("the reference rejects liboqs's ML-DSA-65 signature")

    # ML-KEM-768: both decapsulate each other's ciphertexts to the same secret.
    seed = hashlib.sha256(b"qrdx kat ml-kem-768 d").digest()
    seed += hashlib.sha256(b"qrdx kat ml-kem-768 z").digest()
    ek, dk = ML_KEM_768.key_derive(seed)
    ss, ct = ML_KEM_768._encaps_internal(ek, hashlib.sha256(b"qrdx kat ml-kem-768 m").digest())
    if oqs.KeyEncapsulation("ML-KEM-768", dk).decap_secret(ct) != ss:
        raise SystemExit("liboqs decapsulates the reference ML-KEM-768 ciphertext differently")
    ct2, ss2 = oqs.KeyEncapsulation("ML-KEM-768").encap_secret(ek)
    if ML_KEM_768.decaps(dk, ct2) != ss2:
        raise SystemExit("the reference decapsulates liboqs's ML-KEM-768 ciphertext differently")

    OUT.write_text(
        TEMPLATE.format(
            liboqs=oqs.oqs_version(),
            pk=pk.hex(),
            msg=msg.hex(),
            sig=sig.hex(),
            dk=dk.hex(),
            ct=ct.hex(),
            ss=ss.hex(),
        )
    )
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
